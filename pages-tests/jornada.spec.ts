import { expect, test } from '@playwright/test';
const prefix = '/AppSecTrail';
test('navegação, perfil, aula, diagnóstico e backup funcionam sob a base', async ({ browser }) => {
  const first = await browser.newContext();
  const page = await first.newPage();
  const broken: string[] = [];
  page.on('response', response => { if (response.status() >= 400 && response.url().startsWith('http://127.0.0.1:4324/')) broken.push(`${response.status()} ${response.url()}`); });
  await page.goto(`${prefix}/`);
  await page.getByRole('link', { name: 'Perfil', exact: true }).click();
  await expect(page).toHaveURL(/\/AppSecTrail\/perfil\//);
  const name = page.getByRole('textbox', { name: 'Nome ou apelido' });
  await expect(name).toBeEnabled(); await name.fill('Ana');
  await page.getByRole('button', { name: 'Salvar perfil' }).click();
  await expect(page.getByText('Perfil salvo neste navegador.', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Biblioteca', exact: true }).click();
  await page.getByRole('link', { name: 'HTTP: requisições e respostas' }).click();
  await expect(page).toHaveURL(/\/AppSecTrail\/biblioteca\/http-essencial\//);
  await expect(page.getByText('Visita salva no perfil.')).toBeVisible();
  await page.getByRole('button', { name: 'Marcar aula como concluída' }).click();
  await expect(page.getByText('Registro salvo no perfil.')).toBeVisible();
  await page.getByLabel('A mensagem enviada pelo servidor em retorno à requisição.').check();
  await page.getByRole('button', { name: 'Verificar resposta' }).click();
  await expect(page.getByText('Tentativa salva no perfil local.')).toBeVisible();
  await page.getByRole('link', { name: 'Trilhas', exact: true }).click();
  await expect(page.getByText('Concluída no perfil local')).toBeVisible();
  await page.getByRole('link', { name: 'Diagnóstico', exact: true }).click();
  await page.getByLabel('O servidor').check(); await page.getByLabel('GET', { exact: true }).check();
  await page.getByRole('button', { name: 'Finalizar avaliação' }).click();
  await expect(page.getByText('Avaliação salva no perfil.')).toBeVisible();
  await page.reload(); await expect(page.getByText(/HTTP v1: 2\/2/)).toBeVisible();
  await page.getByRole('link', { name: 'Perfil', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Nome ou apelido' })).toHaveValue('Ana');
  const exportButton = page.getByRole('button', { name: 'Exportar perfil JSON' });
  await expect(exportButton).toBeEnabled();
  const download = page.waitForEvent('download'); await exportButton.click();
  const path = await (await download).path(); if (!path) throw new Error('Backup indisponível');
  const second = await browser.newContext(); const other = await second.newPage();
  await other.goto(`${prefix}/perfil/`);
  await other.getByLabel('Selecionar backup JSON').setInputFiles(path);
  await other.getByRole('button', { name: 'Confirmar importação' }).click();
  await expect(other.getByText(/Perfil importado/)).toBeVisible();
  await other.reload();
  await expect(other.getByRole('textbox', { name: 'Nome ou apelido' })).toHaveValue('Ana');
  await expect(other.getByText(/http-essencial.*concluída/)).toBeVisible();
  await other.getByRole('link', { name: 'Diagnóstico', exact: true }).click();
  await expect(other.getByText(/HTTP v1: 2\/2/)).toBeVisible();
  expect(broken).toEqual([]);
  await first.close(); await second.close();
});
